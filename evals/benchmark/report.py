"""Tables for results/REPORT.md, generated from results/metrics.json so every number is traceable.

    python -m evals.benchmark.report --metrics evals/benchmark/results/metrics.json > evals/benchmark/results/TABLES.md
"""
import argparse
import json
from pathlib import Path


def pct(p):
    """'k/n (x%, 95% CI a-b%)' from a wilson() result."""
    if not p or not p.get("n"):
        return "n/a (0 cases)"
    return f"{p['k']}/{p['n']} ({100 * p['value']:.0f}%, 95% CI {100 * p['low']:.0f}-{100 * p['high']:.0f}%)"


def kap(k, boot=None):
    if not k or k.get("value") is None:
        return "n/a"
    text = f"{k['value']:.2f} (95% CI {k['low']:.2f} to {k['high']:.2f})"
    if boot and boot.get("low") is not None:
        text += f"; bootstrap {boot['low']:.2f} to {boot['high']:.2f}"
    return text


def agreement_rows(name, a):
    return [
        f"| {name} | exact | {pct(a['exact'])} |",
        f"| | within one level | {pct(a['within_one'])} |",
        f"| | weighted kappa (quadratic) | {kap(a['kappa_quadratic'], a.get('kappa_quadratic_bootstrap'))} |",
        f"| | weighted kappa (linear) | {kap(a['kappa_linear'])} |",
        f"| | under-triage (less urgent than reference) | {pct(a['under_triage'])} |",
        f"| | over-triage | {pct(a['over_triage'])} |",
        f"| | reference 1-2 given 1-2 (high-acuity sensitivity) | {pct(a['high_acuity_sensitivity'])} |",
        f"| | reference 1-2 given 3 or lower | {pct(a['high_acuity_missed_to_3_plus'])} |",
        f"| | reference 1 given 1-2 | {pct(a['level_1_caught_at_1_2'])} |",
    ]


def confusion(a):
    c = a["confusion"]
    lines = ["| reference \\ AI | " + " | ".join(map(str, c["columns_predicted"])) + " |",
             "|---|" + "---|" * len(c["columns_predicted"])]
    for level, row in zip(c["rows_reference"], c["counts"]):
        lines.append(f"| {level} | " + " | ".join(map(str, row)) + " |")
    return lines


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--metrics", type=Path, required=True)
    args = parser.parse_args(argv)
    m = json.loads(args.metrics.read_text())
    out = ["<!-- Generated by python -m evals.benchmark.report from metrics.json; do not edit by hand. -->", ""]
    for key, r in m["esi"].items():
        out += [f"### {r['label']} (`{key}`)", "",
                f"Cases: {r['cases']}; reference levels {r['reference_levels']}; outcomes {r['outcomes']}; "
                f"AI levels {r['ai_levels']}.", "",
                f"AI gave an ESI level: {pct(r['ai_gave_a_level'])}. Reference 1-2 patients, all of them: "
                + "; ".join(f"{k} {pct(v)}" for k, v in r["reference_1_2_all_cases"].items()) + ".", "",
                "| Comparison | Metric | Result |", "|---|---|---|"]
        out += agreement_rows("AI vs reference", r["ai_vs_reference"])
        if r.get("nurse_vs_reference"):
            out += agreement_rows("Triage nurse vs experts", r["nurse_vs_reference"])
        if r.get("simple_rule_vs_reference"):
            s = r["simple_rule_vs_reference"]
            out += [f"| Simple vitals rule vs reference | exact | {pct(s['exact'])} |",
                    f"| | weighted kappa (quadratic) | {kap(s['kappa_quadratic'])} |",
                    f"| | reference 1-2 given 1-2 | {pct(s['high_acuity_sensitivity'])} |"]
        maj = r["majority_class_exact"]
        out += [f"| Always level {maj['level']} (most common reference) | exact | {pct(maj)} |", ""]
        out += ["AI vs reference, counts:", ""] + confusion(r["ai_vs_reference"]) + [""]
    c = m["consistency"]
    out += ["### Consistency", "", "| Set | Cases | Same ESI in every repeat | Within one level | Kappa repeat 1 vs 2 |",
            "|---|---|---|---|---|"]
    for name in ("purav", "mimic", "ktas"):
        if name in c:
            x = c[name]
            out.append(f"| {name} | {x['cases_all_repeats_usable']} (repeats {x['repeats_per_case']}) | "
                       f"{pct(x['identical_esi_all_repeats'])} | {pct(x['esi_within_one_all_repeats'])} | "
                       f"{kap(x['kappa_quadratic_repeat1_vs_repeat2'])} |")
    d = c["digits_vs_spoken_words"]
    out += ["", f"Same 421 ambulance patients, numbers in digits vs spoken as words: identical ESI {pct(d['identical'])}, "
                f"within one {pct(d['within_one'])}.", ""]
    g = m["guardrail_mutation_tests"]
    out += ["### Guardrails", "", f"Unmodified real outputs (repeat 1) naming a number the reports don't state: "
            f"{pct(m['model_unsupported_numbers_on_real_outputs'])}.", "", "| Test | Caught |", "|---|---|"]
    for name, value in g["handoff_number_check"].items():
        if isinstance(value, dict):
            out.append(f"| Handoff number check: {name.replace('_', ' ')} | {pct(value)} |")
    out.append(f"| (mutants made) | {g['handoff_number_check']['mutants']} |")
    for name, value in g["extraction_quote_check"].items():
        out.append(f"| Extraction quote check: {name.replace('_', ' ')} | {pct(value)} |")
    out += ["", "### Vital sign extraction", "", "| Set | Runs | Recall | Precision |", "|---|---|---|---|"]
    for name, e in m["extraction"].items():
        out.append(f"| {name} | {e['runs']} | {pct(e['recall_all_vitals'])} | {pct(e['precision_all_vitals'])} |")
    out += ["", "| Set | Vital | Recall | Precision |", "|---|---|---|---|"]
    for name, e in m["extraction"].items():
        for vital, v in e["per_vital"].items():
            out.append(f"| {name} | {vital} | {pct(v['recall'])} | {pct(v['precision'])} |")
    o = m["operations"]
    out += ["", "### Speed and cost (measured on these calls)", "", "| Step | Attempts | Errors | Median latency | p90 | Mean tokens in/out | List-price cost per call |",
            "|---|---|---|---|---|---|---|"]
    for name in ("assessment", "extraction"):
        x = o[name]
        cost = f"${x['list_price_usd_per_call']:.5f}" if x["list_price_usd_per_call"] is not None else "n/a"
        out.append(f"| {name} | {x['attempts']} | {x['errors']} | {x['latency_ms_median'] / 1000:.1f} s | "
                   f"{x['latency_ms_p90'] / 1000:.1f} s | {x['input_tokens_mean']:.0f} / {x['output_tokens_mean']:.0f} | {cost} |")
    out += ["", f"Prices used (USD per million tokens in, out): {o['price_per_million_tokens_used']} "
                "(backend/case_assessment.py PRICES_PER_MILLION)."]
    print("\n".join(out))


if __name__ == "__main__":
    main()
